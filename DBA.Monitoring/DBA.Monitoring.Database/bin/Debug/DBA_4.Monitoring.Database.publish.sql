			   f.io_stall,
			   f.size_on_disk_bytes
	        
	FROM sys.dm_io_virtual_file_stats(NULL, NULL) AS f 
	WHERE f.[database_id] NOT IN (
	                               DB_ID(N'master'),
								   DB_ID(N'model'),
								   32767 -- RESOURCE db  
								  ); 

IF XACT_STATE() = 1 
