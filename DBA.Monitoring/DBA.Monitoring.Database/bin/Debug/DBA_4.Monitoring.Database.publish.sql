DECLARE  @counter_snapshot_id INT;

BEGIN TRY 

	BEGIN TRAN; 

	--Getting snapshot ID 
	EXEC dbo.RegisterCounterSnapshot 
										@counter_snapshot_type_id = 3 ,  -- "File Stats"
